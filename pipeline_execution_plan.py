"""Read-only validation of pipeline execution and invalidation plans."""

import argparse
from pathlib import Path

from pipeline_stages import STAGES, downstream_stages, select_stages
from pipeline_preflight import REQUIRED_INPUTS, SUPPORTED

ROOT = Path(__file__).resolve().parent

PROTECTED = {
    "outputs/01_raw_extract.parquet",
    "outputs/02_master_flagged.parquet",
    "outputs/03_scored.parquet",
    "models/train_val_test_indices.json",
    "models/train_val_test_indices_v2.json",
    "models/learned_weights_v2.json",
    "models/clinical_baseline_weights.json",
}


def validate_plan(selected):
    downstream = downstream_stages(selected)
    affected = list(dict.fromkeys(selected + downstream))

    outputs = {
        relative
        for stage in affected
        for relative in STAGES[stage]["outputs"]
    }

    selected_outputs = {
        relative
        for stage in selected
        for relative in STAGES[stage]["outputs"]
    }

    required = {
        relative
        for stage in selected
        for relative in REQUIRED_INPUTS.get(stage, [])
    }

    errors = []

    unsupported = set(selected) - SUPPORTED

    if unsupported:
        errors.append(
            "Execution not enabled for stages: "
            + ", ".join(sorted(unsupported))
        )

    protected_overlap = outputs & PROTECTED

    if protected_overlap:
        errors.append(
            "Protected artifacts would be affected: "
            + ", ".join(sorted(protected_overlap))
        )

    # Inputs generated by selected stages require ordered execution.
    # Until that is implemented, block all such plans.
    regenerated_inputs = required & selected_outputs

    if regenerated_inputs:
        errors.append(
            "Selected stages regenerate required inputs: "
            + ", ".join(sorted(regenerated_inputs))
        )

    # Inputs invalidated by downstream stages must not be removed.
    downstream_outputs = {
        relative
        for stage in downstream
        for relative in STAGES[stage]["outputs"]
    }

    invalidated_inputs = required & downstream_outputs

    if invalidated_inputs:
        errors.append(
            "Downstream invalidation overlaps required inputs: "
            + ", ".join(sorted(invalidated_inputs))
        )

    print("\nEXECUTION SAFETY PLAN")
    print("=" * 65)
    print("Selected stages:", selected)
    print("Downstream invalidated:", downstream)
    print("Affected output paths:", len(outputs))
    print("Required input paths:", len(required))

    if errors:
        print("\nPLAN BLOCKED")
        for error in errors:
            print(" -", error)
        return False

    print("\nPLAN PASSED")
    print("No protected artifacts or required inputs would be invalidated.")
    print("DRY RUN: No files modified.")
    return True


def main():
    parser = argparse.ArgumentParser()

    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--stage")
    group.add_argument("--from", dest="start")
    group.add_argument("--all", action="store_true")

    parser.add_argument("--to", dest="end")

    args = parser.parse_args()

    selected = select_stages(
        stage=args.stage,
        start=args.start,
        end=args.end,
        all_stages=args.all,
    )

    if not validate_plan(selected):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
